import React, { useState, useEffect } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { 
  Building2, Search, FileText, CheckCircle2, Clock, MapPin, Download,
  ChevronRight, ArrowRight, Loader2, PlayCircle, Layers, Sparkles
} from 'lucide-react';
import { supabase } from '../services/supabaseClient';
import { useApp } from '../context/AppContext';
import { notificationService } from '../services/notificationService';
import { storageService } from '../services/storageService';
import { govAssistantService } from '../services/govAssistantService';
import jsPDF from 'jspdf';

export const GovAssistant: React.FC = () => {
  const { language, user, isRtl, trackCarbon } = useApp();
  const [services, setServices] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);
  const [selectedService, setSelectedService] = useState<any | null>(null);
  const [steps, setSteps] = useState<any[]>([]);
  const [progress, setProgress] = useState<any | null>(null);
  const [locations, setLocations] = useState<any[]>([]);
  const [aiGuidance, setAiGuidance] = useState<{ docs: string[], tips: string } | null>(null);

  useEffect(() => {
    fetchServices();
  }, []);

  const fetchServices = async () => {
    setLoading(true);
    try {
      // Fetch gov_services
      const { data, error } = await supabase.from('government_services').select('*').order('id');
      if (error) throw error;
      setServices(data || []);
    } catch (e) {
      console.error(e);
      notificationService.error(isRtl ? 'لم يتم العثور على خدمات المساعد.' : 'Assistant services not found.');
    } finally {
      setLoading(false);
    }
  };

  const handleSelectService = async (service: any) => {
    setSelectedService(service);
    setLoading(true);
    try {
      // Fetch steps
      const { data: stepData } = await supabase.from('service_steps').select('*').eq('service_id', service.id).order('step_order');
      setSteps(stepData || []);

      // Fetch AI Guidance
      const guidance = await govAssistantService.generateDocumentList(service.name);
      setAiGuidance(guidance);

      // Fetch progress
      if (user) {
        let { data: progData } = await supabase.from('user_service_progress').select('*').eq('user_id', user.id).eq('service_id', service.id).single();
        if (!progData) {
          // Init progress
          const { data: newProg } = await supabase.from('user_service_progress').insert({
            user_id: user.id,
            service_id: service.id,
            current_step: 1
          }).select().single();
          progData = newProg;
        }
        setProgress(progData);
      }

      // Fetch locations
      const { data: locData } = await supabase.from('service_locations').select('*').eq('service_id', service.id);
      setLocations(locData || []);
    } catch(e) {
      console.error(e);
    } finally {
      setLoading(false);
    }
  };

  const advanceStep = async (stepOrder: number) => {
    if (!progress || !user) return;
    const isCompleted = stepOrder === steps.length;
    const { data, error } = await supabase.from('user_service_progress').update({
      current_step: isCompleted ? stepOrder : stepOrder + 1,
      completed: isCompleted,
      updated_at: new Date().toISOString()
    }).eq('id', progress.id).select().single();
    
    if (data) {
      setProgress(data);
      if (isCompleted) {
         notificationService.success(isRtl ? 'تم إنهاء الإجراء بنجاح!' : 'Procedure completed successfully!');
         storageService.addGreenCoins(10);
         try {
           await trackCarbon('gov_digital_assistant', 'carbon_reduction', -2.5, {
             service_id: selectedService.id,
             service_name: selectedService.name,
             type: 'Gov_Smart_Assistant_Saved_Trips'
           });
         } catch(e){}
      } else {
         notificationService.success(isRtl ? 'تم التقدم للخطوة التالية!' : 'Progress advanced!');
      }
    }
  };

  const generateDocument = () => {
    if (!user) return;
    const doc = new jsPDF();
    
    doc.setFont("helvetica");
    doc.setFontSize(22);
    doc.text("Official Service Request Form", 105, 20, { align: 'center' });
    
    doc.setFontSize(14);
    doc.text(`Service: ${selectedService?.name}`, 20, 40);
    doc.text(`Date: ${new Date().toLocaleDateString()}`, 20, 50);
    
    doc.setLineWidth(0.5);
    doc.line(20, 55, 190, 55);
    
    doc.setFontSize(12);
    doc.text(`Applicant Name: ${user.name || user.displayName || user.email}`, 20, 70);
    doc.text(`National ID: ${user.nationalId || '12345678901234'}`, 20, 80);
    doc.text(`Email: ${user.email}`, 20, 90);
    doc.text(`Phone: ${user.phone || 'N/A'}`, 20, 100);
    
    doc.setFontSize(10);
    doc.text("Generated by MoEco Digital Assistant", 105, 280, { align: 'center' });
    
    doc.save(`${selectedService?.name || 'document'}_form.pdf`);
    notificationService.success(isRtl ? 'تم إنشاء النموذج وتنزيله' : 'Form generated and downloaded');
  };

  if (loading && services.length === 0) {
    return (
      <div className="flex justify-center p-12">
        <Loader2 className="w-12 h-12 animate-spin text-aeon-cyan" />
      </div>
    );
  }

  if (!selectedService) {
    return (
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
        {services.map((s, i) => (
          <div key={i} className="p-8 rounded-[2rem] bg-white dark:bg-zinc-900/50 border border-zinc-200 dark:border-white/10 hover:border-aeon-cyan/50 cursor-pointer transition-all shadow-lg group relative overflow-hidden flex flex-col" onClick={() => handleSelectService(s)}>
            <div className="flex justify-between items-start mb-4">
              <span className="px-3 py-1 bg-aeon-cyan/10 text-aeon-cyan text-[10px] font-black uppercase tracking-widest rounded-full">
                {s.category}
              </span>
              <FileText className="w-6 h-6 text-zinc-400 group-hover:text-aeon-cyan transition-colors" />
            </div>
            <h3 className="text-xl font-black font-arabic mb-2 dark:text-white">{s.name}</h3>
            <p className="text-sm font-bold text-zinc-500 mb-6 flex-grow">{s.description}</p>
            <div className="flex items-center justify-between text-xs font-black text-zinc-400 border-t dark:border-white/10 pt-4">
              <div className="flex items-center gap-2">
                <Clock className="w-4 h-4 text-aeon-gold" />
                {s.estimated_time}
              </div>
              <ArrowRight className={`w-4 h-4 group-hover:translate-x-1 transition-transform ${isRtl ? 'rotate-180' : ''}`} />
            </div>
          </div>
        ))}
      </div>
    );
  }

  const currentStepNum = progress?.current_step || 1;

  return (
    <div className="space-y-8">
      <button onClick={() => setSelectedService(null)} className="flex items-center gap-2 text-xs font-black text-aeon-cyan uppercase tracking-widest hover:text-white transition-colors">
        <ChevronRight className={`w-4 h-4 ${isRtl ? '' : 'rotate-180'}`} />
        {isRtl ? 'عودة للخدمات' : 'Back to Services'}
      </button>

      <div className="bg-white dark:bg-zinc-900/50 p-8 rounded-[3rem] border border-zinc-200 dark:border-white/10 shadow-xl relative overflow-hidden flex flex-col md:flex-row justify-between items-start md:items-center gap-6">
        <div>
          <span className="px-3 py-1 bg-aeon-cyan/10 text-aeon-cyan text-[10px] font-black uppercase tracking-widest rounded-full mb-3 inline-block">
            {selectedService.category}
          </span>
          <h2 className="text-3xl font-black font-arabic dark:text-white mb-2">{selectedService.name}</h2>
          <div className="flex items-center gap-4 text-xs font-bold text-zinc-500">
            <span className="flex items-center gap-1"><Clock className="w-4 h-4" /> {selectedService.estimated_time}</span>
            <span className="flex items-center gap-1 text-emerald-500"><CheckCircle2 className="w-4 h-4" /> {progress?.completed ? (isRtl ? 'مكتمل' : 'Completed') : (isRtl ? 'قيد التنفيذ' : 'In progress')}</span>
          </div>
        </div>
        
        {/* Progress Circle */}
        {steps.length > 0 && (
          <div className="relative w-24 h-24 flex items-center justify-center bg-zinc-50 dark:bg-black/50 rounded-full border dark:border-white/10">
            <svg className="w-full h-full transform -rotate-90 absolute" viewBox="0 0 36 36">
              <path className="text-zinc-200 dark:text-white/10" d="M18 2.0845 a 15.9155 15.9155 0 0 1 0 31.831 a 15.9155 15.9155 0 0 1 0 -31.831" fill="none" stroke="currentColor" strokeWidth="3" />
              <path className="text-aeon-cyan" d="M18 2.0845 a 15.9155 15.9155 0 0 1 0 31.831 a 15.9155 15.9155 0 0 1 0 -31.831" fill="none" stroke="currentColor" strokeWidth="3" strokeDasharray={`${((progress?.completed ? steps.length : currentStepNum) / steps.length) * 100}, 100`} />
            </svg>
            <div className="text-center">
              <p className="text-xs font-black dark:text-white">{progress?.completed ? steps.length : currentStepNum} / {steps.length}</p>
              <p className="text-[8px] uppercase tracking-widest text-zinc-500">Steps</p>
            </div>
          </div>
        )}
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-8">
        {/* Steps Tracker */}
        <div className="lg:col-span-2 space-y-6">
          <h3 className="text-xl font-black font-arabic dark:text-white mb-6">
            {isRtl ? 'مسار الإجراءات' : 'Procedure Track'}
          </h3>
          <div className="space-y-4">
            {steps.map((step, idx) => {
              const order = step.step_order;
              const isPast = progress?.completed || order < currentStepNum;
              const isCurrent = !progress?.completed && order === currentStepNum;
              
              return (
                <div key={idx} className={`p-6 rounded-[2rem] border transition-all ${isCurrent ? 'bg-aeon-cyan/5 border-aeon-cyan shadow-[0_0_15px_rgba(0,245,255,0.1)]' : (isPast ? 'bg-emerald-500/5 border-emerald-500/30' : 'bg-white/5 border-white/5 opacity-50')}`}>
                  <div className="flex gap-4">
                    <div className="mt-1">
                      {isPast ? (
                        <div className="w-8 h-8 rounded-full bg-emerald-500 flex items-center justify-center text-white"><CheckCircle2 className="w-5 h-5" /></div>
                      ) : isCurrent ? (
                        <div className="w-8 h-8 rounded-full bg-aeon-cyan flex items-center justify-center text-aeon-obsidian font-black">{order}</div>
                      ) : (
                        <div className="w-8 h-8 rounded-full border-2 border-zinc-500 flex items-center justify-center font-black text-zinc-500">{order}</div>
                      )}
                    </div>
                    <div className="flex-grow space-y-3">
                      <h4 className={`text-lg font-black font-arabic ${isPast ? 'text-emerald-500' : isCurrent ? 'text-aeon-cyan' : 'text-zinc-500'}`}>{step.step_text}</h4>
                      
                      {/* AI Generated Documents */}
                      {aiGuidance && idx === 0 && (
                        <div className="bg-emerald-500/5 p-4 rounded-2xl border border-emerald-500/20">
                          <p className="text-[10px] font-black uppercase tracking-widest text-emerald-500 mb-2 flex items-center gap-2">
                             <Sparkles className="w-3 h-3" />
                             {isRtl ? 'قائمة المستندات المقترحة (ذكاء اصطناعي):' : 'AI Suggested Document List:'}
                          </p>
                          <ul className="grid grid-cols-1 md:grid-cols-2 gap-2">
                            {aiGuidance.docs.map((doc: string, i: number) => (
                              <li key={i} className="flex items-center gap-2 text-xs font-bold text-zinc-300">
                                <div className="w-1.5 h-1.5 bg-emerald-500 rounded-full" />
                                {doc}
                              </li>
                            ))}
                          </ul>
                        </div>
                      )}

                      {step.required_documents?.length > 0 && (
                        <div className="bg-black/20 p-4 rounded-2xl">
                          <p className="text-[10px] font-black uppercase tracking-widest text-zinc-500 mb-2">{isRtl ? 'المستندات الأساسية (رسمي):' : 'Core Documents (Official):'}</p>
                          <ul className="grid grid-cols-1 md:grid-cols-2 gap-2">
                            {step.required_documents.map((doc: string, i: number) => (
                              <li key={i} className="flex items-center gap-2 text-xs font-bold text-zinc-300">
                                <FileText className="w-3 h-3 text-aeon-gold text-opacity-70" />
                                {doc}
                              </li>
                            ))}
                          </ul>
                        </div>
                      )}

                      {/* AI Smart Hint Area */}
                      {isCurrent && aiGuidance?.tips && (
                        <div className="flex items-start gap-2 bg-blue-500/10 p-4 rounded-xl border border-blue-500/20 text-blue-400 text-xs font-bold font-arabic">
                          <Layers className="w-4 h-4 shrink-0 mt-0.5" />
                          <div className="space-y-1">
                             <p className="text-[8px] font-black uppercase tracking-widest opacity-60">AI Insight</p>
                             <p>{aiGuidance.tips}</p>
                          </div>
                        </div>
                      )}

                      {/* Action Area */}
                      {isCurrent && (
                        <div className="flex gap-4 pt-3">
                          <button onClick={() => advanceStep(order)} className="px-6 py-3 bg-aeon-cyan text-aeon-obsidian rounded-xl font-black text-xs uppercase tracking-widest hover:scale-105 transition-transform flex items-center gap-2">
                            {isRtl ? 'أنهيت هذه الخطوة' : 'Mark as Done'} <CheckCircle2 className="w-4 h-4" />
                          </button>
                          
                          {(step.step_text.includes("نماذج") || step.step_text.includes("استمارة")) && (
                            <button onClick={generateDocument} className="px-6 py-3 bg-aeon-gold/20 text-aeon-gold rounded-xl font-black text-xs uppercase tracking-widest hover:bg-aeon-gold/30 transition-colors flex items-center gap-2">
                              {isRtl ? 'تجهيز النموذج تلقائياً' : 'Auto-fill Form'} <Download className="w-4 h-4" />
                            </button>
                          )}
                        </div>
                      )}
                    </div>
                  </div>
                </div>
              );
            })}
          </div>
        </div>

        {/* Sidebar Info */}
        <div className="space-y-6">
          {locations.length > 0 && (
            <div className="bg-white dark:bg-zinc-900/50 p-6 rounded-[2rem] border border-zinc-200 dark:border-white/10">
              <h4 className="font-black font-arabic mb-4 flex items-center gap-2 text-zinc-900 dark:text-white">
                <MapPin className="text-red-500" />
                {isRtl ? 'أماكن الخدمة' : 'Service Locations'}
              </h4>
              <div className="space-y-4">
                {locations.map((loc, i) => (
                  <div key={i} className="p-4 bg-zinc-50 dark:bg-white/5 rounded-xl border dark:border-white/5">
                    <p className="font-black text-sm dark:text-white font-arabic mb-1">{loc.name}</p>
                    <p className="text-xs text-zinc-500 font-bold mb-2">{loc.address}</p>
                    <p className="text-[10px] text-aeon-gold font-bold bg-aeon-gold/10 inline-block px-2 py-1 rounded-md">{loc.working_hours}</p>
                  </div>
                ))}
              </div>
            </div>
          )}

          {/* Integration with Digital ID / Account Details */}
          <div className="bg-gradient-to-br from-aeon-obsidian to-[#0a1a1a] p-6 rounded-[2rem] border border-aeon-cyan/20">
            <h4 className="font-black font-arabic mb-4 text-white flex items-center gap-2">
              <Building2 className="text-aeon-cyan" />
              {isRtl ? 'تكامل الهوية الرقمية' : 'Digital ID Sync'}
            </h4>
            <p className="text-xs font-bold text-zinc-400 font-arabic leading-relaxed mb-4">
              {isRtl ? 'يتم ملء النماذج تلقائياً بناءً على بطاقتك الرقمية المسجلة بالتطبيق.' : 'Forms are auto-filled using your registered digital ID data.'}
            </p>
            <div className="bg-white/5 p-4 rounded-xl border border-white/10 space-y-2">
              <div className="flex justify-between items-center text-xs">
                <span className="text-zinc-500 uppercase font-black tracking-widest">Name</span>
                <span className="text-white font-bold">{user?.name || user?.displayName || '•••••'}</span>
              </div>
              <div className="flex justify-between items-center text-xs">
                <span className="text-zinc-500 uppercase font-black tracking-widest">National ID</span>
                <span className="text-white font-bold">{user?.nationalId || '••••••••••••'}</span>
              </div>
            </div>
            <button onClick={generateDocument} className="w-full mt-4 py-3 bg-white/10 hover:bg-white/20 text-white rounded-xl font-black text-xs transition-colors flex items-center justify-center gap-2 font-arabic border border-white/5">
              {isRtl ? 'تحميل بياناتي כمستند' : 'Download My Info'} <Download className="w-4 h-4" />
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
