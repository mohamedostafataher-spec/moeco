-- ملف إعادة بناء قواعد البيانات بالكامل
-- ملاحظة: هذا الكود سيقوم بحذف الجداول القديمة وإعادة إنشائها.
-- تأكد من تنفيذ هذا فقط في قاعدة البيانات الجديدة.

DROP TABLE IF EXISTS consumption_records CASCADE;
DROP TABLE IF EXISTS carbon_activities CASCADE;

-- 1. جدول تسجيلات الاستهلاك بالتفصيل
CREATE TABLE consumption_records (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id UUID NOT NULL,
    sector TEXT NOT NULL,
    value NUMERIC NOT NULL,
    unit TEXT,
    cost NUMERIC DEFAULT 0,
    carbon_impact NUMERIC DEFAULT 0,
    description TEXT,
    record_date TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. جدول أنشطة الكربون (للإحصائيات العامة)
CREATE TABLE carbon_activities (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id UUID NOT NULL,
    activity_type TEXT NOT NULL,
    carbon_impact NUMERIC DEFAULT 0,
    metadata JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    sector TEXT,
    value NUMERIC
);

