-- 1. Enable Extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. Clean up existing tables to prevent duplicate/type errors
DROP TABLE IF EXISTS public.consumption_records CASCADE;
DROP TABLE IF EXISTS public.carbon_activities CASCADE;
DROP TABLE IF EXISTS public.transport_logs CASCADE;
DROP TABLE IF EXISTS public.utility_tiers CASCADE;

-- 3. Profiles Table
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
    full_name_ar TEXT,
    full_name_en TEXT,
    avatar_url TEXT,
    points INTEGER DEFAULT 0,
    total_co2_saved FLOAT DEFAULT 0,
    level INTEGER DEFAULT 1,
    rank TEXT DEFAULT 'Green Starter',
    referral_code TEXT UNIQUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Carbon Activities (Main History)
CREATE TABLE public.carbon_activities (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    activity_type TEXT NOT NULL,
    sector TEXT,
    value FLOAT,
    carbon_impact FLOAT NOT NULL,
    metadata JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Consumption Records (Detailed Calculator Log)
CREATE TABLE public.consumption_records (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    sector TEXT NOT NULL,
    value FLOAT NOT NULL,
    unit TEXT,
    carbon_impact FLOAT,
    cost FLOAT,
    description TEXT,
    record_date DATE DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Utility Tiers (The Pricing Engine)
CREATE TABLE IF NOT EXISTS public.utility_tiers (
    id SERIAL PRIMARY KEY,
    sector TEXT NOT NULL,
    min FLOAT DEFAULT 0,
    max FLOAT,
    price FLOAT,
    carbon_factor FLOAT DEFAULT 0.5
);

-- 6.1 Coupons Table
CREATE TABLE IF NOT EXISTS public.coupons (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title TEXT NOT NULL,
    description TEXT,
    code TEXT NOT NULL,
    discount TEXT,
    expiry_date TIMESTAMPTZ,
    source TEXT NOT NULL,
    link TEXT,
    category TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(code, source)
);

-- 6.2 News & Alerts Table
CREATE TABLE IF NOT EXISTS public.news (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    title TEXT NOT NULL,
    description TEXT,
    content TEXT,
    url TEXT UNIQUE NOT NULL,
    image_url TEXT,
    source TEXT,
    source_url TEXT,
    category TEXT DEFAULT 'all',
    target_screen TEXT DEFAULT 'eco_news',
    is_alert BOOLEAN DEFAULT FALSE,
    alert_type TEXT DEFAULT 'normal',
    priority TEXT DEFAULT 'normal',
    country TEXT DEFAULT 'Egypt',
    published_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6.3 Points Transactions
CREATE TABLE IF NOT EXISTS public.points_transactions (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    amount INTEGER NOT NULL,
    reason TEXT,
    category TEXT DEFAULT 'system',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6.4 User Scores (Leaderboard)
CREATE TABLE IF NOT EXISTS public.user_scores (
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
    total_score INTEGER DEFAULT 0,
    level INTEGER DEFAULT 1,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6.5 RSS Sources
CREATE TABLE IF NOT EXISTS public.rss_sources (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name TEXT NOT NULL,
    url TEXT UNIQUE NOT NULL,
    feed_url TEXT,
    target_screen TEXT DEFAULT 'eco_news',
    category TEXT DEFAULT 'all',
    is_active BOOLEAN DEFAULT TRUE,
    priority_keywords TEXT[],
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6.6 Utility Meters
CREATE TABLE IF NOT EXISTS public.utility_meters (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    type TEXT NOT NULL,
    meter_number TEXT,
    initial_reading FLOAT DEFAULT 0,
    is_estimated BOOLEAN DEFAULT FALSE,
    estimation_method TEXT,
    location TEXT,
    provider TEXT,
    metadata JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6.7 Utility Readings
CREATE TABLE IF NOT EXISTS public.utility_readings (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    meter_id UUID REFERENCES public.utility_meters(id) ON DELETE CASCADE,
    reading_value FLOAT NOT NULL,
    consumption FLOAT NOT NULL,
    cost FLOAT,
    co2_impact FLOAT,
    photo_url TEXT,
    status TEXT DEFAULT 'Actual',
    reading_date DATE DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

